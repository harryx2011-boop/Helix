import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Builds supabase/schema-idempotent.sql from supabase/schema.sql.
 *
 * `schema.sql` is the fresh-project bootstrap and says so: it uses bare
 * `CREATE TABLE`, so running it against a database that already has the schema
 * fails on the first statement. That makes it useless for the thing an operator
 * most often wants — confirming a live project actually matches the migrations,
 * or topping up one that is partly applied.
 *
 * This rewrites the same statements to be safely re-runnable. It is generated,
 * not maintained: regenerate after any migration lands, and the drift check in
 * `check-schema.mjs` covers the source file it derives from.
 *
 *   node supabase/build-schema.mjs && node supabase/build-schema-idempotent.mjs
 */

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, 'schema.sql');
const out = join(here, 'schema-idempotent.sql');

let sql = await readFile(src, 'utf8');

// CREATE TABLE / INDEX / TYPE → guarded. `CREATE TYPE` has no IF NOT EXISTS in
// Postgres, so those two are wrapped in a DO block that swallows duplicate_object.
// Not line-anchored: one CREATE TABLE lives inside an `EXECUTE $sql$ ... $sql$`
// block (the pgvector-conditional `chunks` table), so an anchored pattern misses
// it and the run fails on a database that already has it.
sql = sql.replace(/CREATE TABLE (?!IF NOT EXISTS)/gi, 'CREATE TABLE IF NOT EXISTS ');
sql = sql.replace(/CREATE (UNIQUE )?INDEX (?!IF NOT EXISTS)/gi, 'CREATE $1INDEX IF NOT EXISTS ');
sql = sql.replace(/^CREATE (UNIQUE )?INDEX (?!IF NOT EXISTS)/gim, 'CREATE $1INDEX IF NOT EXISTS ');
sql = sql.replace(/^create (unique )?index (?!if not exists)/gm, 'create $1index if not exists ');

sql = sql.replace(
  /^CREATE TYPE\s+(\w+)\s+AS ENUM\s*\(([^)]*)\);/gim,
  (_m, name, body) =>
    `DO $do$ BEGIN\n  CREATE TYPE ${name} AS ENUM (${body});\nEXCEPTION WHEN duplicate_object THEN NULL;\nEND $do$;`,
);

// A policy cannot be created twice; drop first. Same for triggers.
sql = sql.replace(
  /^create policy (\w+)\s+on (\w+)/gim,
  (_m, policy, table) => `drop policy if exists ${policy} on ${table};\ncreate policy ${policy}\n  on ${table}`,
);
sql = sql.replace(
  /^create trigger (\w+)\s+((?:before|after)[\s\S]*?on (\w+))/gim,
  (_m, trig, rest, table) => `drop trigger if exists ${trig} on ${table};\ncreate trigger ${trig} ${rest}`,
);

// `ALTER TABLE ... ADD COLUMN` and `ADD CONSTRAINT` are the two that repeat.
sql = sql.replace(/add column (?!if not exists)/gim, 'add column if not exists ');
sql = sql.replace(
  /^alter table (\w+)\s+add constraint (\w+)/gim,
  (_m, table, con) => `alter table ${table} drop constraint if exists ${con};\nalter table ${table} add constraint ${con}`,
);

const header = `-- Helix hosted schema, RE-RUNNABLE — GENERATED by supabase/build-schema-idempotent.mjs. Do not edit.
--
-- Derived from schema.sql, which is the fresh-project bootstrap and uses bare
-- CREATE TABLE. This version is safe to run against a database that already has
-- some or all of the schema: on a fully migrated project it is a no-op that
-- proves everything is in place, and on a partial one it fills the gaps.
--
-- It does NOT drop or alter existing data, and it does not remove anything a
-- migration added. It is additive only.
--
-- Regenerate after any migration lands:
--   node supabase/build-schema.mjs && node supabase/build-schema-idempotent.mjs
--
`;

sql = sql.replace(/^-- Helix hosted schema — GENERATED[\s\S]*?\n--\n/, header);

// The source migrations already `drop ... if exists` before most creates, so the
// rewrites above can emit the same line twice. Collapse consecutive duplicates.
sql = sql.replace(/^(drop (?:policy|trigger) if exists [^\n]*;)\n\1$/gim, '$1');

await writeFile(out, sql, 'utf8');
console.log(`wrote ${out}`);
