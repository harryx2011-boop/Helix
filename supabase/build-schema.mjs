import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Builds supabase/schema.sql: one file that takes a FRESH Supabase project to
 * the full hosted schema — the API's own migrations, then the hosted ones.
 *
 * The API records each migration it applies in `schema_migrations` with a
 * sha256 of the file, and refuses to re-run one it has seen. The generated
 * file seeds that table with the same hashes, so an API booting against a
 * project set up this way finds nothing to do rather than failing on
 * `CREATE TABLE api_keys` a second time.
 *
 * Fresh projects only: the API migrations do not use IF NOT EXISTS.
 */

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const apiDir = join(root, 'apps', 'api', 'migrations');
const hostedDir = join(here, 'migrations');
const out = join(here, 'schema.sql');

async function sqlFiles(dir) {
  const names = (await readdir(dir)).filter((f) => f.endsWith('.sql')).sort();
  return Promise.all(names.map(async (name) => ({ name, sql: await readFile(join(dir, name), 'utf8') })));
}

const api = await sqlFiles(apiDir);
const hosted = await sqlFiles(hostedDir);

const banner = (text) => `-- ${'='.repeat(76)}\n-- ${text}\n-- ${'='.repeat(76)}\n`;

const parts = [
  `-- Helix hosted schema — GENERATED by supabase/build-schema.mjs. Do not edit.\n` +
    `--\n` +
    `-- Apply once to a fresh Supabase project (SQL editor or psql). It contains, in\n` +
    `-- order: the API's migrations (apps/api/migrations), the hosted migrations\n` +
    `-- (supabase/migrations), and the schema_migrations rows the API expects to\n` +
    `-- find so it does not re-apply its own files at boot.\n` +
    `--\n` +
    `-- Regenerate after any migration lands:  node supabase/build-schema.mjs\n` +
    `-- Sources: ${api.map((f) => f.name).join(', ')} | ${hosted.map((f) => f.name).join(', ')}\n`,
  banner('API migrations'),
  ...api.map((f) => `-- ---- apps/api/migrations/${f.name}\n${f.sql.trimEnd()}\n`),
  banner('schema_migrations seed (what apps/api/src/db/migrate.ts would have recorded)'),
  `CREATE TABLE IF NOT EXISTS schema_migrations (\n  filename    text PRIMARY KEY,\n  checksum    text        NOT NULL,\n  applied_at  timestamptz NOT NULL DEFAULT now()\n);\n` +
    `INSERT INTO schema_migrations (filename, checksum) VALUES\n` +
    api.map((f) => `  ('${f.name}', '${createHash('sha256').update(f.sql).digest('hex')}')`).join(',\n') +
    `\nON CONFLICT (filename) DO NOTHING;\n`,
  banner('Hosted migrations'),
  ...hosted.map((f) => `-- ---- supabase/migrations/${f.name}\n${f.sql.trimEnd()}\n`),
];

await writeFile(out, parts.join('\n'));
console.log(`wrote ${out}: ${api.length} API + ${hosted.length} hosted migrations`);
